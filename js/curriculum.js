// Il percorso: cosa studiare, in quale ordine, e come sapere di averlo fatto.
//
// Criterio dell'ordine: ogni passo aggiunge UNA difficoltà sola. Un accordo nuovo non
// arriva insieme a un ritmo nuovo, e un ritmo nuovo si prova su un accordo che le dita
// già conoscono.
//
// ── Perché questo ordine e non quello dell'ukulele ────────────────────────────
//
// Sull'ukulele si parte dal Do, che è un dito solo, e il muro non c'è: il pezzo più duro
// del primo anno è il Mi. Sulla chitarra la mappa è un'altra e va rispettata, altrimenti
// si insegna a mollare:
//
//   Si parte dal MI MINORE, non dal Do. Due dita, tutte e sei le corde suonano, non c'è
//   niente da smorzare. Il Do arriva al terzo livello perché chiede tre dita in diagonale
//   E la 6ª corda da non suonare: sono due difficoltà insieme.
//
//   Le corde SMORZATE sono un argomento, non una nota a piè di pagina. Sull'ukulele erano
//   un'eccezione rara; qui metà libreria ha una ✕, e suonare il Mi basso su un Do lo
//   trasforma in un'altra cosa senza che chi impara se ne accorga.
//
//   Il BARRÉ ha un livello suo. È il muro del secondo mese, quello dove si smette: non si
//   attraversa con un passo fra gli altri, ma con una scaletta di mezzi barré, un ordine
//   dal più facile al più duro (Fa♯m prima del Fa, non dopo) e degli esercizi che parlano
//   di polso e di pollice invece che di forza.
//
//   Il FINGERPICKING pesa il doppio. Il pollice alternato e il Travis non sono un livello
//   avanzato: sono il suono della chitarra acustica, e ci si arriva prima del barré.
//
// L'ordine non è un'opinione: `collaudo.html` verifica che nessun passo chieda un accordo
// non ancora introdotto. Le eccezioni esistono ma vanno DICHIARATE in `dati.tollera`,
// così una scorciatoia didattica resta una scelta e non diventa una svista.
//
// Tipi di passo:
//   accordatura — apre l'accordatore, si chiude da sé quando le sei corde sono a posto
//   lettura     — una scheda da leggere, con domanda di controllo
//   accordo     — la forma nuova: la premi, la suoni, la togli, la rimetti
//   ascolta     — il microfono verifica che l'accordo suoni davvero come deve
//   orecchio    — allenamento dell'orecchio: riconoscere senza guardare
//   cambio      — l'esercizio che fa la differenza: due accordi a tempo di metronomo
//   ritmo       — mano destra sul telaio del ritmo (pennata o arpeggio)
//   giro        — suonare un giro o un brano dall'inizio alla fine

