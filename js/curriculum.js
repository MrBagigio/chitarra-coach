export const PASSI = LIVELLI.flatMap((l) => l.passi.map((p) => ({ ...p, livello: l.id })));
export const PER_ID = new Map(PASSI.map((p) => [p.id, p]));

export function passo(id) {
  return PER_ID.get(id) || null;
}

/** Accordi introdotti dal percorso fino a un certo passo (compreso). */
export function accordiFinoA(idPasso) {
  const fine = PASSI.findIndex((p) => p.id === idPasso);
  const entro = fine < 0 ? PASSI : PASSI.slice(0, fine + 1);
  const visti = [];
  entro.forEach((p) => {
    if (p.tipo === 'accordo' && !visti.includes(p.dati.accordo)) visti.push(p.dati.accordo);
  });
  return visti;
}

/** Accordi che l'utente ha già segnato come fatti: alimenta i "cambi a sorteggio". */
export function accordiAppresi(passiFatti) {
  const visti = PASSI
    .filter((p) => p.tipo === 'accordo' && passiFatti[p.id])
    .map((p) => p.dati.accordo);
  return visti.length >= 2 ? visti : ['Em', 'Am', 'G'];
}

/** Il prossimo passo non fatto: è la risposta a "che faccio oggi?". */
export function prossimoPasso(passiFatti) {
  return PASSI.find((p) => !passiFatti[p.id]) || null;
}

export function avanzamentoLivello(livello, passiFatti) {
  const fatti = livello.passi.filter((p) => passiFatti[p.id]).length;
  return { fatti, totale: livello.passi.length, quota: fatti / livello.passi.length };
}
